// Seeded random generator (mulberry32). The same seed always deals the same
// patrol jitter and loot sparkle, which is what makes the staged screenshot
// scenes repeatable frame for frame.

export function createRandom(seed) {
  let a = seed | 0;
  return function random() {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
